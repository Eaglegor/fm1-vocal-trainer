"""Generate the FM1's exercise bank, optionally replacing its example melody."""
import argparse
from pathlib import Path

from trainer import PATTERNS, song, warmup


def write_bank(path, track, channel, output):
    # Store 10 ms ticks at 120 BPM. The panel tempo scales the whole timeline.
    routines = [(key.upper(), warmup(key, 60, 120)) for key in PATTERNS]
    routines.append(("MELODY", song(path, track, channel)))
    lines = ["/* Generated by make_routines.py. Times are 10 ms ticks at 120 BPM. */"]
    totals = []
    for index, (_, steps) in enumerate(routines):
        if len(steps) > 1024 or steps[-1].end > 655:
            raise ValueError("The embedded melody supports up to 1024 notes and 655 seconds.")
        lines.append(f"static const struct practice_step steps_{index}[] = {{")
        total = previous_end = 0
        for step in steps:
            start = round(step.start * 100)
            end = max(start + 1, round(step.end * 100))
            if start < previous_end:
                raise ValueError("Melody notes must be distinguishable at the panel's 10 ms resolution.")
            previous_end = end
            total += end - start
            harmony = step.notes[0] if len(step.notes) == 2 else 255
            lines.append(f"    {{{start}, {end}, {step.target}, {harmony}}},")
        totals.append(total)
        lines.append("};")
    lines.append("static const struct practice_routine routines[] = {")
    lines.append('    {"FREESTYLE", 0, 0, 0},')
    for index, (label, steps) in enumerate(routines):
        lines.append(f'    {{"{label}", steps_{index}, {len(steps)}, {totals[index]}}},')
    lines.append("};")
    output.write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("file", nargs="?", default="example.mid")
    parser.add_argument("--track", type=int, default=0)
    parser.add_argument("--channel", type=int, default=1)
    args = parser.parse_args()
    write_bank(args.file, args.track, args.channel, Path(__file__).parent / "firmware/practice_bank.inc")
